"""Unit tests for the estimator registry and the model sweep."""

from __future__ import annotations

import pandas as pd
import pytest
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import LogisticRegression

from dsjourney import benchmark
from dsjourney.config import SplitConfig
from dsjourney.preprocess import split_and_scale


def test_registries_are_populated() -> None:
    assert "linear" in benchmark.available_models("regression")
    assert "logistic" in benchmark.available_models("classification")
    assert "kmeans" in benchmark.available_models("clustering")


def test_available_models_rejects_an_unknown_task() -> None:
    with pytest.raises(ValueError, match="unknown task"):
        benchmark.available_models("telepathy")


def test_build_model_returns_the_right_class() -> None:
    assert isinstance(benchmark.build_model("regression", "random_forest"), RandomForestRegressor)


def test_build_model_passes_hyperparameters_through() -> None:
    model = benchmark.build_model("regression", "random_forest", n_estimators=7)
    assert model.n_estimators == 7


def test_config_params_override_registry_defaults() -> None:
    """The registry supplies max_iter=1000; a config that also sets it must win."""
    model = benchmark.build_model("classification", "logistic", max_iter=42)
    assert isinstance(model, LogisticRegression)
    assert model.max_iter == 42


def test_build_model_names_the_alternatives_on_a_typo() -> None:
    with pytest.raises(KeyError, match="available:"):
        benchmark.build_model("regression", "randmo_forest")


def test_compare_models_ranks_regressors(regression_frame: pd.DataFrame) -> None:
    split = split_and_scale(regression_frame, "target", SplitConfig(test_size=0.3))
    result = benchmark.compare_models(
        "regression",
        split.x_train,
        split.y_train,
        split.x_test,
        split.y_test,
        models=["linear", "decision_tree", "knn"],
    )
    assert list(result.table.columns)[:2] == ["model", "r2"]
    assert result.table["r2"].is_monotonic_decreasing
    assert result.best_name == "linear"  # the data is generated by a linear rule
    assert result.best_score > 0.9


def test_compare_models_ranks_ascending_for_error_metrics(regression_frame: pd.DataFrame) -> None:
    split = split_and_scale(regression_frame, "target", SplitConfig(test_size=0.3))
    result = benchmark.compare_models(
        "regression",
        split.x_train,
        split.y_train,
        split.x_test,
        split.y_test,
        models=["linear", "decision_tree"],
        rank_by="rmse",
    )
    assert result.table["rmse"].is_monotonic_increasing


def test_compare_models_ranks_classifiers(classification_frame: pd.DataFrame) -> None:
    split = split_and_scale(classification_frame, "target", SplitConfig(test_size=0.3))
    result = benchmark.compare_models(
        "classification",
        split.x_train,
        split.y_train,
        split.x_test,
        split.y_test,
        models=["logistic", "decision_tree", "gaussian_nb"],
    )
    assert result.best_score > 0.85
    assert result.table["error"].isna().all()


def test_compare_models_records_a_failure_without_aborting(
    classification_frame: pd.DataFrame,
) -> None:
    """MultinomialNB cannot take negative inputs; the sweep must survive it."""
    split = split_and_scale(classification_frame, "target", SplitConfig(test_size=0.3))
    result = benchmark.compare_models(
        "classification",
        split.x_train,
        split.y_train,
        split.x_test,
        split.y_test,
        models=["logistic", "multinomial_nb"],
    )
    assert result.best_name == "logistic"
    assert len(result.table) == 2


def test_compare_models_rejects_clustering(regression_frame: pd.DataFrame) -> None:
    split = split_and_scale(regression_frame, "target", SplitConfig())
    with pytest.raises(ValueError, match="does not support task"):
        benchmark.compare_models(
            "clustering", split.x_train, split.y_train, split.x_test, split.y_test
        )


def test_compare_models_explains_a_total_failure(regression_frame: pd.DataFrame) -> None:
    """Text columns reaching a numeric sweep used to raise a cryptic KeyError."""
    text_frame = regression_frame.assign(feature_a="not a number")
    split = split_and_scale(text_frame, "target", SplitConfig(test_size=0.3))
    with pytest.raises(RuntimeError, match="every candidate model failed"):
        benchmark.compare_models(
            "regression",
            split.x_train,
            split.y_train,
            split.x_test,
            split.y_test,
            models=["linear", "ridge"],
        )


def test_compare_text_models_ranks_tfidf_pipelines(review_frame: pd.DataFrame) -> None:
    from dsjourney import text

    documents = text.normalise_series(review_frame["text"])
    labels = (review_frame["stars"] >= 4).astype(int)
    polar = labels[review_frame["stars"] != 3]
    docs = documents[review_frame["stars"] != 3]

    result = benchmark.compare_text_models(
        docs[:14],
        polar[:14],
        docs[14:],
        polar[14:],
        models=["logistic", "linear_svc"],
        min_df=1,
    )
    assert list(result.table.columns)[:2] == ["model", "f1"]
    assert result.table["f1"].is_monotonic_decreasing
    assert hasattr(result.best_model, "named_steps")


def test_compare_text_models_records_a_failure(review_frame: pd.DataFrame) -> None:
    """GaussianNB cannot take the sparse matrix a vectoriser produces."""
    from dsjourney import text

    documents = text.normalise_series(review_frame["text"])
    labels = (review_frame["stars"] >= 4).astype(int)
    result = benchmark.compare_text_models(
        documents[:16],
        labels[:16],
        documents[16:],
        labels[16:],
        models=["logistic", "gaussian_nb"],
        min_df=1,
    )
    assert result.best_name == "logistic"
    assert result.table["error"].notna().any()
